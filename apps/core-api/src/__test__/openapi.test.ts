import { expect, test } from "bun:test";
import { SQL } from "bun";
import { openapi } from "../openapi.ts";
import { createCoreAccountApplication } from "../public/account.ts";

const published = () => Bun.file(new URL("../../../../docs/openapi.json", import.meta.url)).json();

test("the published OpenAPI document matches the contract generated by Core", async () => {
  expect(await published()).toEqual(JSON.parse(JSON.stringify(openapi())));
});

test("the Core public listener serves the published OpenAPI document without credentials", async () => {
  const db = new SQL("postgres://unused:unused@127.0.0.1:1/unused", { max: 1 });
  try {
    const app = createCoreAccountApplication({
      db,
      pepper: "synthetic-platform-pepper-0123456789",
      trustedProxyCidrs: [],
    });
    const response = await app.request("/openapi.json");
    expect(response.status).toBe(200);
    expect(response.headers.get("cache-control")).toBe("no-store");
    expect(await response.json()).toEqual(await published());
  } finally {
    await db.close();
  }
});
